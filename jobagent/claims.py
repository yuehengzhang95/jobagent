"""Claims bank: the only facts the Tailor may use.

kind=resume  -> a bullet/summary from main.tex (verified; the only source of numbers)
kind=detail  -> qualitative detail extracted from artifacts (methods, tools, design)
"""
import re
from typing import List, Optional, Set

import yaml
from pydantic import BaseModel

from . import config, paths

_NUM = re.compile(r"\d[\d,]*(?:\.\d+)?")


def numbers(text: str) -> Set[str]:
    """Numeric tokens, normalized ('1,208' -> '1208', '0.90' -> '0.9')."""
    out = set()
    for tok in _NUM.findall(text):
        tok = tok.replace(",", "")
        if "." in tok:
            tok = tok.rstrip("0").rstrip(".")
        out.add(tok)
    return out


class Claim(BaseModel):
    id: str
    kind: str  # resume | detail
    role_id: str
    project: Optional[str] = None
    text: str
    source: str


def load() -> List[Claim]:
    bank = [Claim(**c) for c in yaml.safe_load(paths.CLAIMS_YAML.read_text())["claims"]]
    for pub in config.profile().get("optional_publications", []):
        bank.append(Claim(id=pub["id"], kind="resume", role_id="publications", text=pub["text"],
                          source="config/profile.yaml (optional publication)"))
    return bank


def save(claims: List[Claim]) -> None:
    paths.CLAIMS_YAML.parent.mkdir(parents=True, exist_ok=True)
    header = ("# Generated by `python -m jobagent librarian`. Review and edit freely:\n"
              "# delete any detail claim that is wrong; resume claims mirror main.tex.\n")
    body = yaml.safe_dump({"claims": [c.model_dump() for c in claims]}, sort_keys=False,
                          allow_unicode=True, width=120)
    paths.CLAIMS_YAML.write_text(header + body)


def render_for_prompt(claims: List[Claim]) -> str:
    lines = []
    for c in claims:
        where = f"{c.role_id}" + (f" / {c.project}" if c.project else "")
        lines.append(f"[{c.id}] ({c.kind}; {where}) {c.text}")
    return "\n".join(lines)
